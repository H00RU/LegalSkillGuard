"""Generative local policy proposals for the two native scalar tasks.

Public source pointers remove verbatim-copy burden without supplying any
semantic rule. New statements and local alternatives are generated by Qwen;
the deterministic layer handles Python syntax, source links and execution.
"""
from copy import deepcopy
import re

from .native_schema import obj,array,STRING
from .projection import compact
from .safe_program import execute,local_choices,local_execution_table,native_square,validate
from .local_credit import preference


def source_index(record):
    public=record['public']
    if record['dataset']=='SARA_v2_Binary':
        source='\n'.join('SECTION '+s+'\n'+text for s,text in public['rules_context'].items())
    elif record['dataset']=='RuleArena_Airline':source=public['rules']
    else:raise ValueError('Native scalar proposal task not supported')
    spans=[]
    for match in re.finditer(r'[^\n]+',source):
        if match[0].strip():spans.append({'id':len(spans),'start':match.start(),'end':match.end(),'text':match[0]})
    return source,spans


def proposal_schema(index):
    return obj({'program':STRING})


def proposal_prompt(record):
    source,index=source_index(record);public=record['public'];dataset=record['dataset']
    if dataset=='SARA_v2_Binary':case={k:public[k] for k in ('facts','query')};result='bool (True means Entailment) or the exact string Entailment/Contradiction'
    else:case={'current_passenger_and_all_bags':public['prompt']};result='the exact integer total ticket plus all bag fees'
    instruction='Write only a short executable Python solve() for this case. Return '+result+'. Read the provision named in the question and preserve its relevant conditions. Instantiate current facts as ordinary Python values. Use named local quantities and a final return expression composing them. Implement only the policy branches relevant to this current case; do not enumerate an entire policy or invent threshold sequences. Every variable must be defined by actual Python values, never a list of document references. No imports, print, eval/exec, file/network or oracle calls. Ordinary Python arithmetic, logic, min/max/sum/len/range are available. Output only {"program":Python_source_string}. Source attribution and alternative proposals are a separate later step; do not produce them here.'
    return [{'role':'system','content':'Generate executable source semantics. No thinking, explanation or markdown; only the specified JSON.'},
            {'role':'user','content':instruction+'\nDATASET='+dataset+'\nCURRENT_CASE='+compact(case)+'\nPUBLIC_POLICY:\n'+source}],source,index


def analyze(record,proposal):
    source,index=source_index(record);expected=record['grade']['answer'];dataset=record['dataset']
    result={'dataset':dataset,'source':record['key'],'source_hash':record['runtime_public_sha256'],
            'proposal_generated_by_model':True,'gold_used_for_output_repair':False,'fallback':False}
    try:validate(proposal['program'])
    except Exception as e:return {**result,'program_valid':False,'error':type(e).__name__+': '+str(e),'local_tables':[]}
    execution=execute(proposal['program'],record['public'],dataset)
    result.update(program_valid=execution['valid'],execution=execution,native_expected=expected,
                  native_correct=execution.get('answer')==expected if execution['valid'] else False)
    resolved=deepcopy(proposal)
    for block in resolved.get('blocks',[]):
        sid=block['source_id']
        if type(sid) is not int or not 0<=sid<len(index):raise ValueError('Nonpublic source pointer')
        block.update(quote=index[sid]['text'],source_start=index[sid]['start'])
    blocks=local_choices(resolved,source);tables=[]
    for block in blocks:
        table=local_execution_table(resolved,block,record['public'],dataset,expected,record['key']+':'+block['name'])
        table['credit']=preference(table['loss_table']) if table['loss_table'] else {'status':'no_jointly_executable_context','weight':0.,'preferred':None}
        tables.append(table)
    result['local_tables']=tables;result['M1_stable_blocks']=sum(t['credit']['status']=='stable' for t in tables)
    result['M1_conflicting_blocks']=sum(t['credit']['status']=='conflict' for t in tables)
    result['M2_square']=native_square(resolved,record['public'],dataset,expected,record['key'])
    result['source_rule_semantics_independently_proved']=False
    result['note']='Native TRAIN labels direct execution loss, not proof of complete rule semantics; source pointer and valid Python are not core learning success.'
    return result
